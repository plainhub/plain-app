// Helper: compare 32 little-endian limbs (values 0..255) with L.
// Returns true if `a >= L`.
private fun limbsGeL(a: LongArray): Boolean {
    for (i in 31 downTo 0) {
        val ai = (a[i] and 0xff).toInt()
        val li = L[i].toInt() and 0xff
        if (ai != li) return ai > li
    }
    return true
}

// ── Field arithmetic (radix 2^16, 16 signed limbs) ────────────────────────
// Visibility: `internal` so tests can exercise field operations directly.
// Do NOT use from application code — these primitives are not safe to use
// in isolation (no range checks, no constant-time guarantees).

internal fun feCarry(o: Fe) {
    for (i in 0 until 16) {
        o[i] += 1L shl 16
        val c = o[i] shr 16
        o[if (i == 15) 0 else i + 1] += (if (i == 15) 38 else 1) * (c - 1)
        o[i] -= c shl 16
    }
}

internal fun feCMove(p: Fe, q: Fe, b: Int) {
    val c = (b - 1).inv().toLong()
    for (i in 0 until 16) {
        val t = c and (p[i] xor q[i])
        p[i] = p[i] xor t
        q[i] = q[i] xor t
    }
}

internal fun feAdd(o: Fe, a: Fe, b: Fe) {
    for (i in 0 until 16) o[i] = a[i] + b[i]
}

internal fun feSub(o: Fe, a: Fe, b: Fe) {
    for (i in 0 until 16) o[i] = a[i] - b[i]
}

internal fun feMul(o: Fe, a: Fe, b: Fe) {
    val t = LongArray(31)
    for (i in 0 until 16) for (j in 0 until 16) t[i + j] += a[i] * b[j]
    for (i in 0 until 15) t[i] += 38 * t[i + 16]
    for (i in 0 until 16) o[i] = t[i]
    feCarry(o)
    feCarry(o)
}

internal fun feSq(o: Fe, a: Fe) = feMul(o, a, a)

internal fun feInv(o: Fe, a: Fe) {
    val c = a.copyOf()
    for (i in 253 downTo 0) {
        feSq(c, c)
        if (i != 2 && i != 4) feMul(c, c, a)
    }
    c.copyInto(o)
}

// a^((p-5)/8) = a^(2^252 - 3): bits 0,3,5..252 set
internal fun fePow22523(o: Fe, a: Fe) {
    val c = a.copyOf()
    for (i in 250 downTo 0) {
        feSq(c, c)
        if (i != 1) feMul(c, c, a)
    }
    c.copyInto(o)
}

internal fun fePack(o: ByteArray, n: Fe) {
    val t = n.copyOf()
    feCarry(t); feCarry(t); feCarry(t)
    for (j in 0 until 2) {
        val m = LongArray(16)
        m[0] = t[0] - 0xffed
        for (i in 1 until 15) {
            m[i] = t[i] - 0xffff - ((m[i - 1] shr 16) and 1)
            m[i - 1] = m[i - 1] and 0xffff
        }
        m[15] = t[15] - 0x7fff - ((m[14] shr 16) and 1)
        val b = ((m[15] shr 16) and 1).toInt()
        m[14] = m[14] and 0xffff
        feCMove(t, m, 1 - b)
    }
    for (i in 0 until 16) {
        o[2 * i] = (t[i] and 0xff).toByte()
        o[2 * i + 1] = ((t[i] shr 8) and 0xff).toByte()
    }
}

internal fun feUnpack(o: Fe, n: ByteArray) {
    for (i in 0 until 16) {
        o[i] = (n[2 * i].toLong() and 0xff) or ((n[2 * i + 1].toLong() and 0xff) shl 8)
    }
    o[15] = o[15] and 0x7fff
}

internal fun feIsNegative(a: Fe): Int {
    val packed = ByteArray(32)
    fePack(packed, a)
    return packed[0].toInt() and 1
}

internal fun feEqual(a: Fe, b: Fe): Boolean {
    val pa = ByteArray(32); val pb = ByteArray(32)
    fePack(pa, a); fePack(pb, b)
    return pa.contentEquals(pb)
}

// p = 2^255 - 19, encoded little-endian for the Y>=p rejection test.
internal val GF_P_BYTES: ByteArray = byteArrayOf(
    0xed.toByte(), 0xff.toByte(), 0xff.toByte(), 0xff.toByte(), 0xff.toByte(), 0xff.toByte(), 0xff.toByte(), 0xff.toByte(),
    0xff.toByte(), 0xff.toByte(), 0xff.toByte(), 0xff.toByte(), 0xff.toByte(), 0xff.toByte(), 0xff.toByte(), 0xff.toByte(),
    0xff.toByte(), 0xff.toByte(), 0xff.toByte(), 0xff.toByte(), 0xff.toByte(), 0xff.toByte(), 0xff.toByte(), 0xff.toByte(),
    0xff.toByte(), 0xff.toByte(), 0xff.toByte(), 0xff.toByte(), 0xff.toByte(), 0xff.toByte(), 0xff.toByte(), 0x7f.toByte(),
)

// Returns true iff 255-bit (bit 255 cleared) little-endian integer a is >= p.
// Callers pass the raw 32-byte point encoding; byte 31 bit 7 holds the X sign
// and must be stripped before comparison.
internal fun geBytesGtOrEqP(a: ByteArray): Boolean {
    // Scan from MSB (index 31) down to LSB (index 0).  Clear sign bit from a[31].
    var a31 = a[31].toInt() and 0xff
    a31 = a31 and 0x7f
    for (i in 31 downTo 0) {
        val ai = if (i == 31) a31 else a[i].toInt() and 0xff
        val pi = GF_P_BYTES[i].toInt() and 0xff
        if (ai != pi) return ai > pi
    }
    return true // equal to p
}

// ── Point operations (extended twisted Edwards: X, Y, Z, T where T = X*Y/Z) ──
// Internal visibility for unit testing. Do NOT use from application code.

internal fun pointAdd(p: Array<Fe>, q: Array<Fe>) {
    val a = LongArray(16); val b = LongArray(16)
    val c = LongArray(16); val d = LongArray(16)
    val e = LongArray(16); val f = LongArray(16)
    val g = LongArray(16); val h = LongArray(16)
    val t = LongArray(16)

    feSub(a, p[1], p[0])
    feSub(t, q[1], q[0])
    feMul(a, a, t)
    feAdd(b, p[1], p[0])
