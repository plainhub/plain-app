internal fun pointEncode(p: Array<Fe>): ByteArray {
    val zi = LongArray(16)
    feInv(zi, p[2])
    val x = LongArray(16)
    val y = LongArray(16)
    feMul(x, p[0], zi)
    feMul(y, p[1], zi)
    val out = ByteArray(32)
    fePack(out, y)
    out[31] = (out[31].toInt() xor (feIsNegative(x) shl 7)).toByte()
    return out
}

internal fun pointDecode(p: ByteArray): Array<Fe>? {
    if (p.size != 32) return null
    // RFC 8032 §5.1.3: reject y >= p.  `feUnpack` clears bit 255 but y
    // could still be >= p = 2^255 - 19; e.g. y = 2^255 - 16 encodes to
    // a 32-byte value that is perfectly valid after bit 255 clearing
    // but does not represent an element of GF(p).
    if (geBytesGtOrEqP(p)) return null
    val sign = (p[31].toInt() ushr 7) and 1
    val y = LongArray(16)
    feUnpack(y, p)

    val num = LongArray(16)
    val den = LongArray(16)
    feSq(num, y)                  // num = y^2
    feMul(den, num, D)            // den = d * y^2
    feSub(num, num, GF_ONE)       // num = y^2 - 1
    feAdd(den, den, GF_ONE)       // den = d * y^2 + 1

    val den2 = LongArray(16); feSq(den2, den)
    val den4 = LongArray(16); feSq(den4, den2)
    val den6 = LongArray(16); feMul(den6, den4, den2)
    val t = LongArray(16); feMul(t, den6, num); feMul(t, t, den)
    fePow22523(t, t)
    feMul(t, t, num)
    feMul(t, t, den)
    feMul(t, t, den)
    feMul(t, t, den)

    val chk = LongArray(16); feSq(chk, t); feMul(chk, chk, den)
    if (!feEqual(chk, num)) feMul(t, t, I)

    feSq(chk, t); feMul(chk, chk, den)
    if (!feEqual(chk, num)) return null

    val x = t.copyOf()
    if (feIsNegative(x) != sign) feSub(x, GF_ZERO, x)

    return arrayOf(x, y, GF_ONE.copyOf(), LongArray(16).also { feMul(it, x, y) })
}

// ── Scalar reduction mod L (512-bit → 256-bit), table-driven ──────────────
// Internal visibility for unit testing.
//
// Strategy: x mod L = sum_{k=0}^{63} x[k] * 2^{8k} mod L
//                    = sum_{k=0}^{63} x[k] * T[k] mod L,
// where T[k] = MODL_TABLE[k] = 2^{8k} mod L (precomputed).  This is fully
// verifiable, has no tricky signed-shift semantics, no 16*L cleverness, and
// the hottest 32 coefficients (k < 32) are just identity bytes, which the
// optimizer can turn into plain loads.
//
// Rough cost: 64 * 32 multiply-accumulate into 40 limbs, then a short carry
// pass, then up to 8 high-byte reductions using the same table, followed by
// up to 4 conditional subtractions of L.  Acceptable for the signing hot
// path (called 2–3 times per signature) and dramatically safer than the
// hand-optimised TweetNaCl carry chain.

internal fun modL(x: LongArray): ByteArray {
    val a = LongArray(40)
    var k = 0
    while (k < 64) {
        val xk = (x[k] and 0xffL).toInt()
        if (xk != 0) {
            val tbl = MODL_TABLE[k]
            var j = 0
            while (j < 32) {
                a[j] += xk.toLong() * (tbl[j].toLong() and 0xffL)
                j++
            }
        }
        k++
    }
    var carry: Long = 0
    var i = 0
    while (i < 40) {
        val v = a[i] + carry
        a[i] = v and 0xffL
        carry = v ushr 8
        i++
    }
    // Reduce high limbs iteratively until stable.  A single sweep is not
    // enough because the carry from reducing position k can land at
    // position 32+ and must be reduced again.
    var pass = 0
    while (pass < 16) {
        var changed = false
        k = 39
        while (k >= 32) {
            val v = (a[k] and 0xffL).toInt()
            if (v != 0) {
                a[k] = 0
                changed = true
                val tbl = MODL_TABLE[k]
                var c = 0L
                var j = 0
                while (j < 32) {
                    val s = a[j] + c + v.toLong() * (tbl[j].toLong() and 0xffL)
                    a[j] = s and 0xffL
                    c = s ushr 8
                    j++
                }
                var j2 = 32
                while (j2 < 40) {
                    val s = a[j2] + c
                    a[j2] = s and 0xffL
                    c = s ushr 8
                    j2++
                }
            }
            k--
        }
        if (!changed) break
        pass++
    }
    val r = LongArray(32)
    i = 0
    while (i < 32) {
        r[i] = a[i] and 0xffL
        i++
    }
    // Conditionally subtract L until r < L.  With 40-limb reduction the
    // worst-case overshoot is small (~64 * 255 * largest-table-coefficient
    // / 2^256) but a bounded loop is used for safety.
    while (limbsGeL(r)) {
        var borrow: Long = 0
        var j = 0
        while (j < 32) {
            val diff = r[j] - (L[j].toLong() and 0xffL) - borrow
            if (diff < 0) {
                r[j] = diff + 256L
                borrow = 1
            } else {
                r[j] = diff
                borrow = 0
            }
            j++
        }
    }
    val result = ByteArray(32)
    i = 0
    while (i < 32) {
        result[i] = r[i].toByte()
        i++
    }
    return result
}

internal fun reduceModL(hash: ByteArray): ByteArray {
    require(hash.size == 64)
    val x = LongArray(64) { i -> hash[i].toLong() and 0xffL }
    return modL(x)
}

// L as a Little-Endian LongArray for scalar tests (same bytes as the L byte array).
internal val L_LONG: LongArray = LongArray(32) { L[it].toLong() and 0xff }

// ── Public API ────────────────────────────────────────────────────────────

internal fun ed25519DerivePublic(privateKey: ByteArray): ByteArray {
    require(privateKey.size == 32)
    val h = sha512(privateKey)
    val a = h.copyOfRange(0, 32)
    a[0] = (a[0].toInt() and 248).toByte()
    a[31] = (a[31].toInt() and 127).toByte()
    a[31] = (a[31].toInt() or 64).toByte()
    val p = arrayOf(LongArray(16), LongArray(16), LongArray(16), LongArray(16))
    scalarBase(p, a)
    return pointEncode(p)
}

internal fun ed25519Sign(privateKey: ByteArray, message: ByteArray): ByteArray {
    require(privateKey.size == 32)
    val h = sha512(privateKey)
    val a = h.copyOfRange(0, 32)
    a[0] = (a[0].toInt() and 248).toByte()
    a[31] = (a[31].toInt() and 127).toByte()
    a[31] = (a[31].toInt() or 64).toByte()
    val prefix = h.copyOfRange(32, 64)

    // Derive public key from the already-computed scalar a — avoids a
    // redundant SHA-512 in ed25519DerivePublic.
    val ap = arrayOf(LongArray(16), LongArray(16), LongArray(16), LongArray(16))
    scalarBase(ap, a)
    val publicKey = pointEncode(ap)

    // r = SHA-512(prefix || message) mod L
    val rHash = sha512(prefix + message)
    val r = reduceModL(rHash)

    // R = r * B
    val rp = arrayOf(LongArray(16), LongArray(16), LongArray(16), LongArray(16))
    scalarBase(rp, r)
    val rEncoded = pointEncode(rp)

    // k = SHA-512(R || A || message) mod L
    val kHash = sha512(rEncoded + publicKey + message)
    val k = reduceModL(kHash)

    // S = (r + k * a) mod L
    // Multiply unsigned 32-bit limbs byte-by-byte into a 64-limb LongArray,
    // then carry-propagate so every limb fits in a byte.  Without the carry
    // pass, modL's (x[k] and 0xff) would truncate the accumulated products.
    val x = LongArray(64)
    for (i in 0 until 32) {
        x[i] = r[i].toLong() and 0xff
    }
    for (i in 0 until 32) for (j in 0 until 32) {
        x[i + j] += (k[i].toLong() and 0xff) * (a[j].toLong() and 0xff)
    }
    var c: Long = 0
    var i = 0
    while (i < 64) {
        val v = x[i] + c
        x[i] = v and 0xffL
        c = v ushr 8
        i++
    }
    val s = modL(x)

    return rEncoded + s
}

internal fun ed25519Verify(publicKey: ByteArray, message: ByteArray, signature: ByteArray): Boolean {
    if (publicKey.size != 32 || signature.size != 64) return false
    val rEncoded = signature.copyOfRange(0, 32)
    val sEncoded = signature.copyOfRange(32, 64)

    // Check S < L
    var sGeL = false
    for (i in 31 downTo 0) {
        val si = sEncoded[i].toLong() and 0xff
        val li = L[i].toLong() and 0xff
        if (si != li) { sGeL = si > li; break }
    }
    if (sGeL) return false

    // Decode A (public key) and R
    val aPoint = pointDecode(publicKey) ?: return false
    val rPoint = pointDecode(rEncoded) ?: return false

    // k = SHA-512(R || A || message) mod L
    val kHash = sha512(rEncoded + publicKey + message)
    val k = reduceModL(kHash)

    // Check [S]B == R + [k]A
    val sb = arrayOf(LongArray(16), LongArray(16), LongArray(16), LongArray(16))
    scalarBase(sb, sEncoded)

    val ka = arrayOf(LongArray(16), LongArray(16), LongArray(16), LongArray(16))
    scalarMult(ka, aPoint, k)

    val rka = arrayOf(
        rPoint[0].copyOf(), rPoint[1].copyOf(),
        rPoint[2].copyOf(), rPoint[3].copyOf(),
    )
    pointAdd(rka, ka)

    return pointEncode(sb).contentEquals(pointEncode(rka))
}

// ── Key generation ────────────────────────────────────────────────────────

internal fun ed25519GenerateKeyPair(): Pair<ByteArray, ByteArray> {
    val privateKey = ByteArray(32)
    val status = privateKey.usePinned { pinned ->
        SecRandomCopyBytes(kSecRandomDefault, privateKey.size.toULong(), pinned.addressOf(0))
    }
    if (status != 0) throw RuntimeException("SecRandomCopyBytes failed")
    val publicKey = ed25519DerivePublic(privateKey)
    return Pair(privateKey, publicKey)
}
