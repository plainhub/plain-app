package com.ismartcoding.plain.ui.web

import androidx.compose.runtime.getValue
import androidx.compose.runtime.mutableStateOf
import androidx.compose.runtime.setValue
import com.ismartcoding.plain.features.settings.PasswordType
import com.ismartcoding.plain.models.PasswordSettings
import kotlinx.coroutines.CancellationException

internal enum class PasswordSettingsOperation { READ, SAVE, GENERATE, TOGGLE }

internal enum class PasswordSettingsError { LOAD, SAVE, GENERATE, ENABLE, MISMATCH, TOO_LONG }

internal class PasswordSettingsState(
    private val readSettings: suspend () -> PasswordSettings,
    private val writePassword: suspend (String) -> Unit,
    private val writeEnabled: suspend (Boolean) -> Unit,
    private val createPassword: suspend () -> String,
) {
    var settings by mutableStateOf<PasswordSettings?>(null)
        private set
    var error by mutableStateOf<PasswordSettingsError?>(null)
        private set
    var operation by mutableStateOf<PasswordSettingsOperation?>(null)
        private set
    val busy get() = operation != null
    var editing by mutableStateOf(false)
        private set
    var password by mutableStateOf("")
        private set
    var confirmation by mutableStateOf("")
        private set
    var generated by mutableStateOf(false)
        private set
    var saved by mutableStateOf(false)
        private set
    private var enableAfterSave = false

    val hasDraft get() = password.isNotEmpty() || confirmation.isNotEmpty()
    val canSave get() = editing && !busy && password.isNotBlank() && confirmation.isNotEmpty()

    suspend fun refresh() {
        if (busy) return
        operation = PasswordSettingsOperation.READ
        try {
            settings = readSettings()
            error = null
        } catch (cancelled: CancellationException) {
            throw cancelled
        } catch (_: Exception) {
            settings = null
            error = PasswordSettingsError.LOAD
        } finally {
            operation = null
        }
    }

    fun edit(enableOnSave: Boolean = false) {
        if (busy || settings == null) return
        clearDraft()
        saved = false
        error = null
        enableAfterSave = enableOnSave || settings?.passwordConfigured == false
        editing = true
    }

    fun updatePassword(value: String) {
        if (busy) return
        password = value
        generated = false
        error = null
    }

    fun updateConfirmation(value: String) {
        if (busy) return
        confirmation = value
        error = null
    }

    fun discard() {
        if (busy) return
        clearDraft()
        editing = false
        error = null
    }

    suspend fun generate() {
        if (busy || !editing) return
        operation = PasswordSettingsOperation.GENERATE
        error = null
        try {
            val value = createPassword()
            check(value.isNotBlank())
            password = value
            confirmation = value
            generated = true
        } catch (cancelled: CancellationException) {
            throw cancelled
        } catch (_: Exception) {
            error = PasswordSettingsError.GENERATE
        } finally {
            operation = null
        }
    }

    suspend fun save() {
        if (!canSave) return
        if (password != confirmation) {
            error = PasswordSettingsError.MISMATCH
            return
        }
        if (password.encodeToByteArray().size > 1024) {
            error = PasswordSettingsError.TOO_LONG
            return
        }
        operation = PasswordSettingsOperation.SAVE
        error = null
        try {
            writePassword(password)
            saved = true
            clearDraft()
            editing = false
            if (enableAfterSave && settings?.passwordType != PasswordType.FIXED) {
                try {
                    writeEnabled(true)
                } catch (cancelled: CancellationException) {
                    throw cancelled
                } catch (_: Exception) {
                    error = PasswordSettingsError.ENABLE
                }
            }
            try {
                settings = readSettings()
            } catch (cancelled: CancellationException) {
                throw cancelled
            } catch (_: Exception) {
                settings = null
                error = PasswordSettingsError.LOAD
            }
        } catch (cancelled: CancellationException) {
            throw cancelled
        } catch (_: Exception) {
            error = PasswordSettingsError.SAVE
        } finally {
            operation = null
        }
    }

    suspend fun setEnabled(enabled: Boolean) {
        if (busy) return
        val current = settings ?: return
        if (enabled && !current.passwordConfigured) {
            edit(enableOnSave = true)
            return
        }
        operation = PasswordSettingsOperation.TOGGLE
        error = null
        saved = false
        try {
            writeEnabled(enabled)
            settings = readSettings()
        } catch (cancelled: CancellationException) {
            throw cancelled
        } catch (_: Exception) {
            settings = null
            error = PasswordSettingsError.LOAD
        } finally {
            operation = null
        }
    }

    fun clearDraft() {
        password = ""
        confirmation = ""
        generated = false
    }
}
