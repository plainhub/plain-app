package com.ismartcoding.plain.lib.kgraphql.generated

import com.ismartcoding.plain.lib.kgraphql.schema.dsl.SchemaBuilder

/**
 * KSP-bridge extension on [SchemaBuilder]. Populates [GeneratedSchemaRegistry]
 * from KSP-generated descriptor objects, then registers every type/input/union/
 * interface via the standard DSL — no `memberPropertiesList()` or
 * `isKotlinSubclassOf` reflection.
 *
 * Generated descriptor objects use `::foo` property references and `KClass::class`
 * references, both of which are KMP-safe (work on iOS / Kotlin-Native without
 * `kotlin.reflect.full`).
 *
 * Call this at the top of your `KGraphQL.schema { ... }` block, before any
 * `query`/`mutation` declarations:
 * ```
 * val schema = KGraphQL.schema {
 *     registerGeneratedSchema()
 *     query("chats") { resolver { -> chatRepo.all() } }
 * }
 * ```
 *
 * NOTE: This function ONLY populates [GeneratedSchemaRegistry]. It does NOT call
 * `type<T> {}` / `inputType<T> {}` directly — those are called explicitly by the
 * user (e.g. `type<ChatItem> { property("data") { ... } }`) or implicitly by
 * [com.ismartcoding.plain.lib.kgraphql.schema.structure.SchemaCompilation] when
 * a type is referenced via a resolver. In both cases, the KSP descriptor is
 * merged automatically, so users do not need to redeclare properties that are
 * already captured by `@GraphQLType` / `@GraphQLInput` annotations.
 *
 * This file lives in `:shared` (not `:shared-lib`) because it calls
 * [registerAllGeneratedSchema], an expect function whose KSP-generated actual
 * is also in `:shared`. Expect/actual pairs must reside in the same Gradle module.
 */
fun SchemaBuilder.registerGeneratedSchema() {
    // Populate the registry from KSP-generated code.
    // The actual is generated by :kgraphql-ksp for each platform target.
    registerAllGeneratedSchema()
}
