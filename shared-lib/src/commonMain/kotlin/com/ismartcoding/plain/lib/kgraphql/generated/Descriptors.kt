package com.ismartcoding.plain.lib.kgraphql.generated

import kotlin.reflect.KClass
import kotlin.reflect.KType

/**
 * Compile-time-fixed description of a single GraphQL field.
 *
 * [accessor] is a KSP-generated lambda `{ it: T -> it.foo }` — a plain
 * method call on every platform. No `KProperty1` handle is kept: on the JVM
 * `KProperty1.get()` resolves through kotlin-reflect metadata by name and
 * signature, which breaks under R8 obfuscation.
 *
 * @param T The parent (owner) type.
 * @param R The field's Kotlin return type.
 */
data class FieldDescriptor<T : Any, R>(
    val name: String,
    val accessor: (T) -> R,
    val returnType: KType,
    val description: String? = null,
    val isIgnored: Boolean = false,
)

/**
 * Compile-time-fixed description of a GraphQL Object or Interface type.
 *
 * Generated by KSP from a `@GraphQLType` / `@GraphQLInterface` annotated class.
 * The SchemaBuilder iterates [fields] and registers each one via the existing
 * `property(KProperty1<T, R>)` DSL — no `memberProperties` reflection.
 *
 * @param isInterface When true, the type is registered as a GraphQL Interface
 *   with [possibleTypes] as its implementing types.
 */
data class TypeDescriptor<T : Any>(
    val kClass: KClass<T>,
    val name: String,
    val isInterface: Boolean = false,
    val fields: List<FieldDescriptor<T, *>> = emptyList(),
    val possibleTypes: List<KClass<*>> = emptyList(),
)

/**
 * Compile-time-fixed description of a GraphQL Union type.
 *
 * Generated by KSP from a `@GraphQLUnion`-annotated sealed class.
 * [members] comes from `KSClassDeclaration.getSealedSubclasses()` at compile
 * time — no `sealedSubclasses` reflection at runtime.
 */
data class UnionDescriptor(
    val kClass: KClass<*>,
    val name: String,
    val members: List<KClass<*>>,
)

/**
 * Compile-time-fixed description of a GraphQL Input type.
 *
 * Generated by KSP from a `@GraphQLInput`-annotated `@Serializable` class.
 * The runtime [com.ismartcoding.plain.lib.kgraphql.schema.execution.ArgumentTransformer]
 * uses [fromMap] (a KSP-generated factory that directly calls the constructor)
 * instead of `primaryConstructor.callBy()` reflection, so iOS is supported.
 *
 * @param optionalParams Constructor parameters with default values. The
 *   runtime allows GraphQL clients to omit these from input objects.
 * @param fromMap KSP-generated factory that creates an instance from a map of
 *   field-name → transformed-value pairs. Replaces `callConstructorBy` reflection.
 *   The generated code directly calls the primary constructor with explicit
 *   field accesses and casts — no runtime reflection.
 */
data class InputDescriptor<T : Any>(
    val kClass: KClass<T>,
    val name: String,
    val fields: List<FieldDescriptor<T, *>>,
    val optionalParams: Set<String>,
    val fromMap: (Map<String, Any?>) -> T,
)

/**
 * Singleton registry populated by KSP-generated `init` blocks when the
 * `registerGeneratedSchema()` SchemaBuilder extension is invoked.
 *
 * The KSP processor generates one file per annotated class declaring an
 * `object` that holds its descriptor, plus a top-level
 * `registerAllGeneratedTypes(into: GeneratedSchemaRegistry)` function that
 * copies every descriptor here. This keeps the registration entry point
 * stable — new types are picked up automatically without touching call sites.
 */
object GeneratedSchemaRegistry {
    val types: MutableMap<KClass<*>, TypeDescriptor<*>> = mutableMapOf()
    val inputs: MutableMap<KClass<*>, InputDescriptor<*>> = mutableMapOf()
    val unions: MutableMap<KClass<*>, UnionDescriptor> = mutableMapOf()
    val interfaces: MutableMap<KClass<*>, TypeDescriptor<*>> = mutableMapOf()

    /** Input serializers bound by `SchemaBuilder.registerGeneratedSchema()`. */
    val inputSerializers: MutableMap<KClass<*>, Any> = mutableMapOf()

    fun <T : Any> registerType(descriptor: TypeDescriptor<T>) {
        types[descriptor.kClass] = descriptor
    }

    fun <T : Any> registerInput(descriptor: InputDescriptor<T>) {
        inputs[descriptor.kClass] = descriptor
    }

    fun registerUnion(descriptor: UnionDescriptor) {
        unions[descriptor.kClass] = descriptor
    }

    fun <T : Any> registerInterface(descriptor: TypeDescriptor<T>) {
        interfaces[descriptor.kClass] = descriptor
    }
}
